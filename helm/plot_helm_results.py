#!/usr/bin/env python3
"""
HELM Analysis: Plotting Results

Plots the results generated by run_helm_analysis.py.
"""

import matplotlib
matplotlib.use("Agg")

import os
import sys
import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
import numpy as np

# Import style_icml from parent directory
sys.path.append('..')
try:
    import style_icml
except ImportError:
    print("Warning: style_icml not found, using default style.")

RESULT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'result')

def plot_helm_results():
    results_path = os.path.join(RESULT_DIR, 'helm_results.csv')
    if not os.path.exists(results_path):
        print(f"Error: Results file not found at {results_path}")
        print("Run run_helm_analysis.py first.")
        sys.exit(1)

    df_results = pd.read_csv(results_path)
    print("Loaded results:")
    print(df_results)

    # Melt dataframe for plotting
    rmse_melt = df_results.melt(
        value_vars=['rmse_mean', 'rmse_rasch', 'rmse_amortized'],
        var_name='Model', value_name='RMSE'
    )
    auc_melt = df_results.melt(
        value_vars=['auc_mean', 'auc_rasch', 'auc_amortized'],
        var_name='Model', value_name='AUC'
    )

    model_map = {
        'rmse_mean': 'Global Mean', 'rmse_rasch': 'Rasch-IRT', 'rmse_amortized': 'Amortized IRT',
        'auc_mean': 'Global Mean', 'auc_rasch': 'Rasch-IRT', 'auc_amortized': 'Amortized IRT'
    }
    rmse_melt['Model'] = rmse_melt['Model'].map(model_map)
    auc_melt['Model'] = auc_melt['Model'].map(model_map)

    model_order = ['Global Mean', 'Rasch-IRT', 'Amortized IRT']
    
    # Colors
    colors = sns.color_palette("muted")
    
    # Plot AUC
    fig, ax = plt.subplots(figsize=(8, 4))
    sns.barplot(
        data=auc_melt,
        x='Model',
        y='AUC',
        order=model_order,
        ax=ax,
        palette="muted"
    )
    ax.set_xlabel('')
    ax.set_ylabel('AUC')
    
    # Add values on top of bars
    for i, v in enumerate(auc_melt.set_index('Model').loc[model_order]['AUC']):
        ax.text(i, v + 0.01, f'{v:.4f}', ha='center')
        
    ax.set_ylim(0.4, 1.0)
    ax.grid(axis='y', linestyle='--', alpha=0.6)
    ax.set_title('HELM Benchmark Analysis - AUC')
    
    plt.tight_layout()
    out = os.path.join(RESULT_DIR, 'auc_comparison_helm.pdf')
    plt.savefig(out, bbox_inches='tight')
    print(f"[OUTPUT] Saved plot: {out}")
    plt.close()

    # Plot RMSE
    fig, ax = plt.subplots(figsize=(8, 4))
    sns.barplot(
        data=rmse_melt,
        x='Model',
        y='RMSE',
        order=model_order,
        ax=ax,
        palette="muted"
    )
    ax.set_xlabel('')
    ax.set_ylabel('RMSE')
    
    # Add values on top of bars
    for i, v in enumerate(rmse_melt.set_index('Model').loc[model_order]['RMSE']):
        ax.text(i, v + 0.005, f'{v:.4f}', ha='center')

    ax.set_ylim(0.0, rmse_melt['RMSE'].max() + 0.1)
    ax.grid(axis='y', linestyle='--', alpha=0.6)
    ax.set_title('HELM Benchmark Analysis - RMSE')
    
    plt.tight_layout()
    out = os.path.join(RESULT_DIR, 'rmse_comparison_helm.pdf')
    plt.savefig(out, bbox_inches='tight')
    print(f"[OUTPUT] Saved plot: {out}")
    plt.close()

if __name__ == '__main__':
    plot_helm_results()
